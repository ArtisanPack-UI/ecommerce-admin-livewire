    /**
     * The localized name of a country, or the code when it is unknown.
     *
     * @since 1.0.0
     *
     * @param  string       $code    The ISO 3166-1 alpha-2 code.
     * @param  string|null  $locale  The display locale; defaults to the app locale.
     *
     * @return string
     */
    public static function name( string $code, ?string $locale = null ): string
    {
        $code = strtoupper( trim( $code ) );

        if ( ! in_array( $code, self::CODES, true ) ) {
            return $code;
        }

        $name = Locale::getDisplayRegion( '-' . $code, $locale ?? app()->getLocale() );

        return '' === $name ? $code : $name;
    }

    /**
     * Select options sorted by localized name.
     *
     * @since 1.0.0
     *
     * @param  string|null  $locale  The display locale; defaults to the app locale.
     *
     * @return array<int, array{id: string, name: string}>
     */
    public static function options( ?string $locale = null ): array
    {
        $locale ??= app()->getLocale();
        $collator = new Collator( $locale );

        $options = array_map(
            static fn ( string $code ): array => [ 'id' => $code, 'name' => self::name( $code, $locale ) ],
            self::CODES,
        );

        usort( $options, static fn ( array $a, array $b ): int => (int) $collator->compare( $a['name'], $b['name'] ) );

        return $options;
    }
}
